import { useState } from 'react'
import { api, type AskResponse, type Source } from '../api'

export default function Ask() {
  const [question, setQuestion] = useState('')
  const [topK, setTopK] = useState(5)
  const [result, setResult] = useState<AskResponse | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [asking, setAsking] = useState(false)

  async function onSubmit(e: React.FormEvent) {
    e.preventDefault()
    if (!question.trim()) return
    setAsking(true)
    setError(null)
    setResult(null)
    try {
      setResult(await api.ask(question.trim(), topK))
    } catch (err) {
      setError((err as Error).message)
    } finally {
      setAsking(false)
    }
  }

  return (
    <div className="space-y-6">
      <form onSubmit={onSubmit} className="space-y-3">
        <label htmlFor="question" className="block text-sm font-semibold">
          Ask a question about your documents
        </label>
        <textarea
          id="question"
          rows={3}
          value={question}
          onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) onSubmit(e)
          }}
          placeholder="e.g. How many days of annual leave do employees get?"
          className="block w-full border border-gray-300 p-2 text-sm focus:border-gray-900 focus:outline-none"
        />
        <div className="flex items-center gap-4">
          <button
            type="submit"
            disabled={asking || !question.trim()}
            className="border border-gray-900 bg-gray-900 px-4 py-1.5 text-sm text-white disabled:border-gray-300 disabled:bg-gray-300"
          >
            {asking ? 'Searching…' : 'Ask'}
          </button>
          <label className="text-sm text-gray-600">
            Passages to retrieve{' '}
            <select
              value={topK}
              onChange={(e) => setTopK(Number(e.target.value))}
              className="ml-1 border border-gray-300 px-1 py-0.5"
            >
              {[3, 5, 8, 10].map((n) => (
                <option key={n}>{n}</option>
              ))}
            </select>
          </label>
        </div>
      </form>

      {error && <p className="text-sm text-red-700">{error}</p>}
      {result && <Answer result={result} />}
    </div>
  )
}

function Answer({ result }: { result: AskResponse }) {
  const mockLLM = result.llm.provider === 'mock'

  return (
    <div className="space-y-6">
      <section>
        <h2 className="mb-2 text-sm font-semibold">Answer</h2>
        <div
          className={`border p-4 text-sm whitespace-pre-wrap ${
            result.insufficient_context || mockLLM ? 'border-amber-300 bg-amber-50' : 'border-gray-200'
          }`}
        >
          {result.answer}
        </div>
        <p className="mt-1 text-xs text-gray-500">
          Generated by {result.llm.provider}:{result.llm.model}
        </p>
      </section>

      <section>
        <h2 className="mb-2 text-sm font-semibold">Sources ({result.sources.length})</h2>
        {result.sources.length === 0 ? (
          <p className="text-sm text-gray-600">
            No relevant passages found. Upload documents or check that they finished processing.
          </p>
        ) : (
          <ol className="space-y-2">
            {result.sources.map((s) => (
              <SourceItem key={s.chunk_id} source={s} />
            ))}
          </ol>
        )}
      </section>
    </div>
  )
}

function SourceItem({ source }: { source: Source }) {
  const [open, setOpen] = useState(source.cited)

  return (
    <li className="border border-gray-200 text-sm">
      <button
        type="button"
        onClick={() => setOpen(!open)}
        className="flex w-full flex-wrap items-baseline gap-x-3 px-3 py-2 text-left hover:bg-gray-50"
      >
        <span className="font-mono">[{source.source_number}]</span>
        <span className="font-medium break-all">{source.filename}</span>
        <span className="text-gray-600">
          {source.page_number != null ? `page ${source.page_number}` : `chunk ${source.chunk_index}`}
        </span>
        <span className="text-gray-600">score {source.score.toFixed(3)}</span>
        {source.cited && <span className="text-xs font-medium text-green-700">cited</span>}
        <span className="ml-auto text-gray-500">{open ? 'Hide' : 'Show'} passage</span>
      </button>
      {open && (
        <p className="border-t border-gray-200 bg-gray-50 px-3 py-2 whitespace-pre-wrap">{source.content}</p>
      )}
    </li>
  )
}
